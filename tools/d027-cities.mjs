      spine(b, 30, 3); b.put(64, 29, 3, 1); guardOf(b, 58, 26); houses(b, 30, [6, 12, 20, 40]);
      b.road(10, 40, 30, 40, 2); houses(b, 40, range(12, 28, 4));
      b.put(20, 47, 1, 2, { den: 3, we: 1 }).put(26, 48, 1, 1, { den: 2, we: 0 }).put(50, 45, 1, 3, { den: 4, we: 2 });
