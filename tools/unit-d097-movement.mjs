import assert from 'node:assert/strict';
import { advanceMovement } from '../src/sim/transitMovement.ts';
const p = x => ({ x, z: 0, height: 0 });
const graph = { revision: 1, edges: [0,1,2].map(x => ({ mode: 'rail', a: p(x), b: p(x+1) })) };
const initial = { mode: 'rail', path: [p(0), p(1), p(2), p(3)], segment: 0, elapsed: 0, minutesPerEdge: 3 };
const before = structuredClone(initial);
let repeated = initial;
for (let i = 0; i < 7; i++) repeated = advanceMovement(graph, repeated, 1).state;
assert.deepEqual(repeated, advanceMovement(graph, initial, 7).state);
assert.deepEqual(initial, before);
assert.equal(repeated.segment, 2); assert.equal(repeated.elapsed, 1);
const cut = { ...graph, edges: graph.edges.slice(0,2) };
let boundary = initial, last;
for (let i = 0; i < 6; i++) { last = advanceMovement(cut, boundary, 1); boundary = last.state; }
const batchBoundary = advanceMovement(cut, initial, 6);
assert.equal(last.status, 'blocked');
assert.deepEqual(last, batchBoundary);
assert.equal(batchBoundary.state.segment, 2); assert.equal(batchBoundary.state.elapsed, 0);
assert.deepEqual(advanceMovement(cut, initial, 7), advanceMovement(cut, batchBoundary.state, 1));
const blocked = advanceMovement(cut, repeated, 12);
assert.equal(blocked.status, 'blocked'); assert.deepEqual(blocked.state, repeated);
assert.equal(advanceMovement(graph, blocked.state, 2).status, 'arrived');
const paused = advanceMovement(graph, initial, 9, true);
assert.equal(paused.status, 'paused'); assert.deepEqual(paused.state, initial);
assert.equal(advanceMovement(graph, initial, 9).status, 'arrived');
assert.equal(advanceMovement(graph, { ...initial, mode: 'tram' }, 9).status, 'blocked');
assert.throws(() => advanceMovement(graph, { ...initial, path: [p(0), p(2)] }, 1));
assert.throws(() => advanceMovement(graph, initial, 172801));
assert.throws(() => advanceMovement(graph, { ...initial, elapsed: 3 }, 1));
console.log('D097 movement: batching, pause, severance, repair and validation pass');
