const range = (a, c, s = 1) => { const o = []; for (let x = a; x <= c; x += s) o.push(x); return o; };
// 主街與電廠；消防局與警察局各一（火災與犯罪只影響「有沒有房子被燒／停稅」，跟這一張的公式無關，覆蓋只是讓城少受隨機事件干擾）
function spine(b, rc = 3, x0 = 4, x1 = 66, z = 30) { b.road(x0, z, x1, z, rc); b.put(x0 - 1, z, 5); return b; }
const guard = (b, x = 12) => b.put(x, 31, 6, 1).put(x + 4, 31, 11, 1);
// 南側一排 1×1 住宅（z=31），略過被佔的格；回傳實際放了幾棟
function houses(b, xs, z = 31, k = 1) { let n = 0; for (const x of xs) if (b.isFree(x, z, 1)) { b.put(x, z, k, 1 + (n % 3), { den: 1 + (n % 5), we: n % 3 }); n++; } return n; }
