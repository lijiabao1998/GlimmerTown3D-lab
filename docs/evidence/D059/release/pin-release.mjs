import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root = process.cwd();
const source = '484cf85bbc8f09192646068bce3617fe69b3e672';
const approved = '284a2538f79d7d0097abbab55b80fa47995cfcb5';
const release = 'b8954fcae4d3b80bc49b6512fb7622f69d711998';
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', timeout: 10000 }).trim();
const sha = b => createHash('sha256').update(b).digest('hex');
assert.equal(git('rev-parse', 'HEAD'), release);
assert.equal(git('rev-parse', 'origin/main'), release);
assert.equal(git('status', '--porcelain'), '');
const tree = git('rev-parse', release + '^{tree}');
assert.equal(tree, git('rev-parse', approved + '^{tree}'));
const changed = git('diff', '--name-only', source, approved).split('\n').filter(Boolean);
assert.ok(changed.every(f => f.endsWith('.md') || f.startsWith('docs/')), 'candidate closure changed documentation and evidence only');
const product = ['src/cityView.ts', 'src/render/cityScene.ts', 'src/content/britishVillage.ts', 'src/render/britishVillageArt.ts'];
const files = Object.fromEntries(product.map(f => {
  const hashes = Object.fromEntries([source, approved, release].map(commit => [commit, sha(execFileSync('git', ['show', commit + ':' + f], { cwd: root, maxBuffer: 10 * 1024 * 1024, timeout: 10000 }))]));
  hashes.workingFile = sha(fs.readFileSync(path.join(root, f)));
  assert.equal(new Set(Object.values(hashes)).size, 1, f);
  return [f, hashes];
}));
const pr = JSON.parse(execFileSync('gh', ['api', 'repos/lijiabao1998/GlimmerTown3D-lab/pulls/16'], { encoding: 'utf8', timeout: 30000 }));
assert.equal(pr.merged, true); assert.equal(pr.merge_commit_sha, release); assert.equal(pr.head.sha, approved);
const html = fs.readFileSync(path.join(root, 'dist/index.html'));
assert.equal(html.length, 1237602); assert.equal(sha(html), '4515f6a815d3450a1b7b271000955d4ed57fe6a8b2f694cbc73e0b4d8b24a8a8');
const report = { checkedAt: new Date().toISOString(), source, approved, release, tree, candidateClosureChangedPaths: changed, sourceByteComparisons: files, localDist: { bytes: html.length, sha256: sha(html) }, pullRequest: { url: pr.html_url, number: pr.number, merged: pr.merged, mergedAt: pr.merged_at, headSha: pr.head.sha, mergeCommitSha: pr.merge_commit_sha }, local: { HEAD: git('rev-parse', 'HEAD'), originMain: git('rev-parse', 'origin/main'), clean: true }, qualification: 'Exact merge and source identity only. CI, Pages and actual public HTTPS are separate evidence.' };
fs.writeFileSync(path.join(root, 'scratch/d059-release/release-identity.json'), JSON.stringify(report, null, 2));
console.log('PASS release identity', release, tree, html.length, sha(html));
